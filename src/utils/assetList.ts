export type AssetIssuerOption = {
  asset: string;
  issuer: string;
};

export const ASSET_ISSUER_OPTIONS: AssetIssuerOption[] = ASSET_ISSUER_CSV.trim()
  .split("\n")
  .map((line) => {
    const [asset, issuer] = line.split(",");
    return {
      asset: normalizeAssetName(asset),
      issuer: normalizeIdentity(issuer),
    };
  })
  .filter((option) => option.asset && option.issuer);

export const ASSET_TO_ISSUER = new Map(ASSET_ISSUER_OPTIONS.map((option) => [option.asset, option.issuer]));

// The QRaffle contract rejects these assets in raffle bundles — QRAFFLE shares
// and QXMR are reserved for dividends/registration (see createAssetRaffle in
// QRaffle.h). Keep them out of the bundle picker; token raffles are unaffected.
export const BUNDLE_EXCLUDED_ASSETS = new Set(["QRAFFLE", "QXMR"]);

export const BUNDLE_ASSET_OPTIONS = ASSET_ISSUER_OPTIONS.filter(
  (option) => !BUNDLE_EXCLUDED_ASSETS.has(option.asset),
);
